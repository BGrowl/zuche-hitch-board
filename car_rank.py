# 3) 打分逻辑
# ======================================================================
_YEAR = re.compile(r"^(19|20)\d{2}\s*")
_SUFFIX = re.compile(r"(尊享版|大师版|大师|荣耀|豪华版|新锐|六座版|七座版|四座版|"
                     r"至尊版|旗舰版|精英版|舒适版|领先版|臻选版|超值版)$")


def _norm(name):
    """去掉前导年份与配置后缀：'2023沃尔沃S90' -> '沃尔沃S90'"""
    s = (name or "").strip()
    s = _YEAR.sub("", s)
    s = _SUFFIX.sub("", s)
    return s


def brand_of(name):
    """按最长匹配识别品牌（'东风猛士M817' -> 东风猛士，而不是 东风）"""
    n = _norm(name).upper()
    best, blen = "", 0
    for b in BRAND:
        u = b.upper()
        if u in n and len(u) > blen:
            best, blen = b, len(u)
    return best


def level_of(name, body=""):
    n = _norm(name).upper()
    for k in SERIES_L3:
        if k.upper() in n:
            return 3
    for k in SERIES_L2:
        if k.upper() in n:
            return 2
    b = body or ""
    if "中大型" in b or "大型" in b:
        return 3
    if "中型" in b:
        return 2
    if "MPV" in b:
        return 2
    return 1


def match_key(name):
    """在 MODEL_SCORE 里找最长的命中键；没命中返回 ''"""
    n = _norm(name).upper()
    best, blen = "", 0
    for k in MODEL_SCORE:
        if k.upper() in n and len(k) > blen:
            best, blen = k, len(k)
    return best


def score(name, body=""):
    bf = BRAND_FORCE.get(brand_of(name))
    if bf is not None:                                    # 品牌强制档最优先
        return bf
    k = match_key(name)
    if k:
        return MODEL_SCORE[k]
    lv = level_of(name, body)
    bonus = BONUS_L3 if lv == 3 else (BONUS_L2 if lv == 2 else 0)
    return BRAND.get(brand_of(name), 50) + bonus


def detail(name, body=""):
    b = brand_of(name)
    k = match_key(name)
    forced = BRAND_FORCE.get(b)
    return {
        "score": score(name, body),
        "matched": ("品牌强制(%s)" % b) if forced is not None else (k or "(品牌兜底)"),
        "brand": b,
        "level": level_of(name, body),
    }


# ======================================================================
# 4) 预览：按类别打印当前排序
# ======================================================================
def main():
    src = os.path.join(HERE, "hitch-site", "data.json")
    if not os.path.exists(src):
        src = os.path.join(HERE, "hitch-all.json")
    j = json.load(open(src, encoding="utf-8"))
    items = j.get("items") or []

    import collections
    seen = collections.OrderedDict()
    for it in items:
        nm = (it.get("model") or it.get("modelName") or "").strip()
        if not nm:
            continue
        seen.setdefault((it.get("cls") or "", nm), []).append(it)

    for g in ("高端车", "新能源", "普通车"):
        rows = [(k[1], len(v)) for k, v in seen.items() if k[0] == g]
        rows.sort(key=lambda r: (-score(r[0]), r[0]))
        print("【%s】%d 车型 / %d 条" % (g, len(rows), sum(c for _, c in rows)))
        for nm, cnt in rows:
            d = detail(nm)
            flag = "" if d["matched"] != "(品牌兜底)" else "  ← 兜底"
            print("   %3d  %-20s ×%-4d%s" % (d["score"], nm, cnt, flag))
        print()


if __name__ == "__main__":
    main()
